#!/usr/bin/env bash
# Refresh the go-cli skill: upgrade every example in assets/ to the latest
# dependencies, re-verify (gofmt, vet, test -race, golangci-lint), report what
# moved, and with --write copy the new go.mod/go.sum back and re-sync
# references/*.md: the line counts on its `→ Read assets/...` pointers and the
# Contents blocks (assets are the source of truth; the docs hold no copies).
#
# Usage (Linux, macOS, or WSL; not Git Bash on Windows - see SKILL.md):
#   scripts/refresh.sh            # dry run: upgrade + verify in a temp dir
#   scripts/refresh.sh --write    # same, then write results into the skill
#   scripts/refresh.sh --sync     # only re-sync docs from assets (after editing an asset)
set -euo pipefail

SKILL=$(cd "$(dirname "$0")/.." && pwd)
MODE=${1:-}
case $MODE in
  "" | --write | --sync) ;;
  *) echo "refresh: unknown argument '$MODE' (use --write or --sync)" >&2; exit 2 ;;
esac

sync_docs() {
  python3 - "$SKILL" <<'PY'
import pathlib, re, sys
root = pathlib.Path(sys.argv[1])
ptr_pat = re.compile(r"→ Read \[`assets/(\S+?)`\]\(\.\./assets/\S+?\) \((\d+) lines")
toc_pat = re.compile(r"<!-- toc -->\n.*?<!-- /toc -->\n\n", re.S)

def headings(lines):
    # (line number, heading) for ## and ### outside fenced code blocks
    out, fenced = [], False
    for i, line in enumerate(lines, 1):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and re.match(r"#{2,3} ", line):
            out.append((i, line))
    return out

def with_toc(text):
    # A contents block after the H1 with line numbers, so an agent can Read just
    # one section (offset/limit) of a long reference. Only for files > 150 lines.
    body = toc_pat.sub("", text)
    if body.count("\n") <= 150:
        return body
    h1_end = body.index("\n") + 1
    toc = ""
    for _ in range(3):  # line numbers depend on the block's own length; settle it
        candidate = body[:h1_end] + "\n" + toc + body[h1_end:].lstrip("\n")
        rows = [f"- L{n} {'  ' if h.startswith('###') else ''}{h.lstrip('#').strip()}"
                for n, h in headings(candidate.split("\n"))]
        new_toc = ("<!-- toc -->\nContents (line numbers for Read offset; regenerated by "
                   "`scripts/refresh.sh --sync`):\n\n" + "\n".join(rows) + "\n<!-- /toc -->\n\n")
        if new_toc == toc:
            break
        toc = new_toc
    return body[:h1_end] + "\n" + toc + body[h1_end:].lstrip("\n")
for md in sorted((root / "references").glob("*.md")):
    text = md.read_text(encoding="utf-8")
    def repl(m):  # keep each pointer's line count current; a missing file fails
        n = (root / "assets" / m.group(1)).read_text(encoding="utf-8").count("\n")
        return m.group(0).replace(f"({m.group(2)} lines", f"({n} lines")
    new, n = ptr_pat.subn(repl, text)
    new = with_toc(new)
    if new != text:
        md.write_text(new, encoding="utf-8", newline="\n")
    print(f"  {md.name}: {n} asset pointers{' (updated)' if new != text else ''}")
PY
}

if [[ $MODE == --sync ]]; then
  echo "Syncing references from assets:"; sync_docs; exit 0
fi

for tool in go golangci-lint python3; do
  command -v "$tool" >/dev/null || { echo "refresh: $tool not found on PATH" >&2; exit 1; }
done

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
cp -r "$SKILL/assets/." "$WORK/"

# GITHUB_TOKEN, when set (as in CI), avoids the anonymous rate limit on shared IPs.
latest() { curl -fsS ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} "https://api.github.com/repos/$1/releases/latest" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p'; }
echo "Toolchain (installed -> latest):"
echo "  go            $(go env GOVERSION) -> $(curl -fsS 'https://go.dev/VERSION?m=text' | head -1)"
echo "  golangci-lint $(golangci-lint version --short 2>/dev/null || golangci-lint --version | awk '{print $4}') -> $(latest golangci/golangci-lint)"
echo "  goreleaser    -> $(latest goreleaser/goreleaser)"
echo "  task          -> $(latest go-task/task)"

direct() { go list -m -f '{{if and (not .Main) (not .Indirect)}}{{.Path}} {{.Version}}{{end}}' all | sort; }

fail=0
for dir in "$WORK"/*/; do
  name=$(basename "$dir")
  echo; echo "== $name"
  cd "$dir"
  [[ -f go.sum ]] && before=$(direct) || before=""
  go get -u -t ./... >/dev/null 2>&1 || true
  go mod tidy
  after=$(direct)
  diff <(echo "$before") <(echo "$after") | sed -n 's/^> /  upgraded: /p' || true
  if [[ -n $(gofmt -l .) ]]; then echo "  FAIL gofmt: $(gofmt -l . | tr '\n' ' ')"; fail=1; fi
  go vet ./... || { echo "  FAIL vet"; fail=1; }
  go test -race -count=1 ./... || { echo "  FAIL test"; fail=1; }
  golangci-lint run --config "$WORK/tool/.golangci.yml" ./... || { echo "  FAIL lint"; fail=1; }
done

echo
if (( fail )); then
  echo "refresh: verification FAILED - assets left unchanged. Fix the example, then re-run." >&2
  exit 1
fi
echo "All examples pass with the latest dependencies."

if [[ $MODE == --write ]]; then
  for dir in "$WORK"/*/; do
    name=$(basename "$dir")
    cp "$dir/go.mod" "$SKILL/assets/$name/go.mod"
    [[ -f $dir/go.sum ]] && cp "$dir/go.sum" "$SKILL/assets/$name/go.sum"
  done
  echo "Wrote go.mod/go.sum into assets/. Syncing references:"; sync_docs
  echo "Now update the Versions table in SKILL.md (and the 'checked' date) from the output above."
else
  echo "Dry run. Re-run with --write to keep the upgrades."
fi
